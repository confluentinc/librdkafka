int main_0192_gzip_decompress(int argc, char **argv) {
        const size_t expected_len = 300000;
        uint64_t decompressed_len = 0;
        char *decompressed;
        size_t i;

        decompressed = rd_gz_decompress_limited(
            compressed, sizeof(compressed), &decompressed_len, expected_len);
        TEST_ASSERT(decompressed, "Decompression failed");
        TEST_ASSERT(decompressed_len == expected_len,
                    "Expected %" PRIusz " bytes, got %" PRIu64, expected_len,
                    decompressed_len);
        for (i = 0; i < expected_len; i++)
                TEST_ASSERT(decompressed[i] == 'a',
                            "Unexpected byte at position %" PRIusz, i);
        TEST_ASSERT(decompressed[decompressed_len] == '\0',
                    "Decompressed data is not nul-terminated");
        rd_free(decompressed);

        decompressed_len = 0;
        decompressed =
            rd_gz_decompress_limited(compressed, sizeof(compressed),
                                     &decompressed_len, expected_len - 1);
        TEST_ASSERT(!decompressed,
                    "Decompression exceeded the configured output limit");

        return 0;
}

